// Only operates on start_ui_test.ps1's isolated app and synthetic media.
import { chromium } from '../.tools/ui-test/node_modules/playwright-core/index.mjs';
import assert from 'node:assert/strict';
import path from 'node:path';
import fs from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { openEditor, openEncoding, finishEditor } from './encoding_ui_helpers.mjs';
let browser;
for (let i = 0; i < 100; i++) {
  try { browser = await chromium.connectOverCDP('http://127.0.0.1:' + process.env.VINYLMV_TEST_PORT); break; }
  catch (error) { if (i === 99) throw error; await new Promise(r => setTimeout(r, 300)); }
}
let main;
for (let i = 0; i < 100; i++) { main = browser.contexts().flatMap(c => c.pages()).find(p => p.url().endsWith('/index.html')); if (main) break; await new Promise(r => setTimeout(r, 200)); }
await main.waitForFunction(() => window.Startup?.phase === 'ready' && state.audio?.title === '湖畔来信' && state.dependencies?.ready);
assert(await main.evaluate(() => !state.rendering && !batchExporter.isRunning()));
const directory = path.resolve(import.meta.dirname, '../.test-output/标题栏编码验证', String(Date.now()));
await fs.mkdir(directory, { recursive: true });
const errors = []; main.on('pageerror', e => errors.push(e.message));
const saved = () => main.evaluate(() => JSON.parse(JSON.stringify({ encoding: prefs.encoding, container: prefs.container, fileName: document.getElementById('fileName').value })));
const original = await saved();
const position = await main.evaluate(() => {
  const entry = document.getElementById('openEncodingPanel'), reset = document.getElementById('resetSettings');
  const a = entry.getBoundingClientRect(), b = reset.getBoundingClientRect();
  return { sameHeader: entry.closest('.panel-header') === reset.closest('.panel-header'), leftOfReset: a.right <= b.left, aligned: Math.abs(a.y - b.y) < 2, width: a.width };
});
assert(position.sameHeader && position.leftOfReset && position.aligned && position.width > 30, '入口位于调整与导出标题栏的重置左侧');
await main.locator('.panel-header').screenshot({ path: path.join(directory, '编码设置位置.png') });
await openEncoding(main);
assert.equal(browser.contexts().flatMap(c => c.pages()).filter(p => p.url().endsWith('/editor.html')).length, 0, '直接打开弹窗，不经过更多设置');
await main.waitForFunction(() => !document.getElementById('refreshEncoders').disabled);
assert.match(await main.locator('#encodingCapabilities').innerText(), /libx264/);
await main.locator('#encMode').selectOption('vbr');
await main.locator('#encBitrate').fill('8'); await main.locator('#encMaxBitrate').fill('4');
await main.locator('#applyEncoding').click();
assert.match(await main.locator('#encodingError').innerText(), /峰值码率不能小于目标码率/);
await main.locator('#encodingDialog button[data-close]').last().click();
assert.deepEqual(await saved(), original, '取消参数修改保持原设置与文件名');
await openEncoding(main);
await main.locator('#encContainer').selectOption('mov');
await main.locator('#encCodec').selectOption('prores');
await main.locator('#resetEncoding').click();
await main.locator('#encodingDialog button[data-close]').first().click();
assert.deepEqual(await saved(), original, '重置草稿后取消不会保存');
await openEncoding(main);
await main.locator('#encContainer').selectOption('mkv');
await main.locator('#encCodec').selectOption('hevc'); await main.locator('#encProfile').selectOption('main');
assert(await main.locator('#encProfile option[value=baseline]').evaluate(o => o.disabled));
await main.locator('#encMode').selectOption('vbr');
await main.locator('#encBitrate').fill('1.5'); await main.locator('#encMaxBitrate').fill('2.5');
await main.locator('#encPreset').selectOption('ultrafast');
await main.locator('#encKeyframe').fill('1'); await main.locator('#encBFrames').fill('0'); await main.locator('#encThreads').fill('2');
await main.locator('#encAudioBitrate').fill('128'); await main.locator('#encSampleRate').selectOption('48000'); await main.locator('#encChannels').selectOption('2');
await main.locator('#applyEncoding').click();
await main.waitForFunction(() => prefs.container === 'mkv');
const expected = (await saved()).encoding;
assert((await main.locator('#fileName').inputValue()).endsWith('.mkv'));
assert.equal(await main.locator('#outputCodec').innerText(), 'H.265 / AAC');
assert.deepEqual(await main.evaluate(() => JSON.parse(localStorage.getItem('preferences')).encoding), expected);
await openEncoding(main);
assert.equal(await main.locator('#encPreset').inputValue(), 'ultrafast');
await main.locator('#encodingDialog button[data-close]').last().click();
let editor = await openEditor(main, browser);
assert.equal(await editor.locator('#openEncoding, #encodingDialog, .editor-encoding').count(), 0, '更多设置中已移除旧编码入口');
await editor.locator('#resetLayout').click(); await finishEditor(editor, false);
assert.deepEqual((await saved()).encoding, expected);
editor = await openEditor(main, browser);
await editor.locator('#resetLayout').click(); await finishEditor(editor);
assert.deepEqual((await saved()).encoding, expected, '应用画面不会覆盖编码设置');
const media = await main.evaluate(() => ({ audio: state.audio, background: state.background }));
await main.reload(); await main.waitForFunction(() => window.Startup?.phase === 'ready' && state.dependencies?.ready);
assert.deepEqual((await saved()).encoding, expected);
assert.equal((await saved()).container, 'mkv');
await main.evaluate(async media => { loadBackground(media.background); await loadAudio(media.audio); }, media);
await main.locator('#resolution').selectOption('480'); await main.locator('#fps').selectOption('24');
await main.locator('#fileName').fill('标题栏编码.mkv');
await main.locator('#outputDirectory').evaluate((e, v) => e.value = v, directory);
await main.locator('#generateButton').click();
await main.waitForFunction(() => document.getElementById('renderTitle').textContent !== '正在生成作品', null, { timeout: 120000 });
assert.equal(await main.locator('#renderTitle').innerText(), '你的作品，完成了', await main.locator('#renderMessage').innerText());
const output = await main.locator('#renderPath').innerText();
const probe = JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-show_streams', '-of', 'json', output], { encoding: 'utf8' }));
assert.equal(probe.streams.find(s => s.codec_type === 'video').codec_name, 'hevc');
assert.equal(probe.streams.find(s => s.codec_type === 'audio').sample_rate, '48000');
assert.equal(probe.streams.find(s => s.codec_type === 'audio').channels, 2);
await main.locator('#renderDialog [data-close]').first().click();
await openEncoding(main); await main.locator('#encContainer').selectOption('mp4');
await main.locator('#resetEncoding').click(); await main.locator('#applyEncoding').click();
assert.deepEqual(errors, []);
await fs.writeFile(path.join(directory, 'result.json'), JSON.stringify({ passed: true, position, output, expected, probe, errors }, null, 2));
console.log('标题栏编码入口、取消、保存、画面编辑独立、持久化与实际 H.265 MKV 导出通过：' + directory);
process.exit(0);
