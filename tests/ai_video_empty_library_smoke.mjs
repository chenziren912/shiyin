// Run after ai_video_smoke.mjs, using its isolated app and local API fixture only.
import { chromium } from '../.tools/ui-test/node_modules/playwright-core/index.mjs';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
const root = path.resolve(import.meta.dirname, '..');
const port = Number(process.env.VINYLMV_TEST_PORT), app = path.resolve(process.env.VINYLMV_TEST_APP || '');
assert(port && app.startsWith(path.join(root, '.test-output', '界面验证-')));
const fixture = JSON.parse(await fs.readFile(path.join(root, '.test-output/ai-fixture-current.json'), 'utf8'));
const directory = path.join(root, '.test-output/AI无视频库验证', String(Date.now()));
await fs.mkdir(directory, { recursive: true });
const browser = await chromium.connectOverCDP(`http://127.0.0.1:${port}`);
const page = browser.contexts().flatMap(context => context.pages()).find(page => page.url().endsWith('/index.html'));
assert(page); assert(await page.evaluate(() => !batchExporter.isRunning()));
const errors = []; page.on('pageerror', error => errors.push(error.message));
const view = await page.evaluate(() => rpc('getAiVideoSettings'));
assert.equal(view.settings.baseUrl, fixture.baseUrl, '仅访问本地模拟服务');
await page.evaluate(settings => rpc('saveAiVideoSettings', { settings }), { ...view.settings, mode: 'missing', failure: 'fail', reuseCache: false, directory: path.join(directory, 'backgrounds') });
const library = await page.evaluate(() => rpc('getVideoLibrary'));
assert(library.every(video => video.path.includes('.test-output')));
await page.evaluate(ids => rpc('removeLibraryVideos', { ids }), library.map(video => video.id));
await page.locator('#batchSelectAll').check(); await page.locator('#batchRemove').click();
const batchFixture = process.argv[2] || process.env.VINYLMV_TEST_BATCH_FIXTURE;
assert(batchFixture, '请传入与隔离程序一致的合成素材目录');
const manifest = JSON.parse(await fs.readFile(path.join(batchFixture, 'manifest.json'), 'utf8'));
const file = manifest.audio[0];
const probe = JSON.parse(execFileSync('ffprobe', ['-v','error','-show_entries','format=duration:format_tags','-of','json',file], { encoding: 'utf8' }));
const tags = probe.format.tags;
const audio = { path: file, title: tags.title, artist: tags.artist, album: tags.album || '', genre: tags.genre || '', duration: Number(probe.format.duration), format: 'MP3', localLyrics: await fs.readFile(file.replace(/\.mp3$/, '.lrc'), 'utf8') };
await page.evaluate(items => batchExporter.open({ items, errors: [] }), [audio]);
await page.waitForFunction(() => !document.getElementById('batchAssign').disabled);
assert.equal((await page.evaluate(() => rpc('getVideoLibrary'))).length, 0);
assert.match(await page.locator('.batch-background').innerText(), /无需先导入视频库/);
await page.locator('#batchOutputDirectory').evaluate((element, value) => { element.value = value; }, directory);
assert((await fetch(fixture.control, { method: 'POST', body: JSON.stringify({ scenario: 'async', reset: true }) })).ok);
await page.locator('#batchStart').click(); await page.waitForFunction(() => batchExporter.isRunning());
await page.waitForFunction(() => !batchExporter.isRunning(), null, { timeout: 240000 });
assert.equal(await page.locator('#batchError').innerText(), '');
assert.equal(await page.locator('.batch-status[data-status=completed]').count(), 1);
const remote = await (await fetch(fixture.status)).json(); assert.equal(remote.creates, 1);
const files = (await fs.readdir(directory)).filter(name => name.endsWith('.mp4')); assert.equal(files.length, 1);
const output = JSON.parse(execFileSync('ffprobe', ['-v','error','-show_entries','stream=codec_name,width,height','-of','json',path.join(directory,files[0])], { encoding:'utf8' }));
assert(output.streams.some(stream => stream.codec_name === 'h264' && stream.height === 480));
assert.deepEqual(errors, []);
await page.screenshot({ path: path.join(directory, '无视频库直接生成.png') });
await fs.writeFile(path.join(directory, 'result.json'), JSON.stringify({ passed: true, remote, files, output, errors }, null, 2));
console.log('空视频库时生成背景并实际导出通过：' + directory);
await browser.close();
