// Checks extended encoders through the workbench header entry.
import { chromium } from '../.tools/ui-test/node_modules/playwright-core/index.mjs';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { openEncoding } from './encoding_ui_helpers.mjs';
const browser = await chromium.connectOverCDP('http://127.0.0.1:' + process.env.VINYLMV_TEST_PORT);
const main = browser.contexts().flatMap(c => c.pages()).find(p => p.url().endsWith('/index.html'));
await main.waitForFunction(() => window.Startup?.phase === 'ready' && state.audio && state.dependencies?.ready);
const directory = path.resolve(import.meta.dirname, '../.test-output/扩展编码界面', String(Date.now()));
await fs.mkdir(directory, { recursive: true });
const errors = []; main.on('pageerror', e => errors.push(e.message));
await main.evaluate(() => document.querySelectorAll('dialog[open]').forEach(d => d.close()));
let editor = await openEncoding(main, browser);
editor.on('pageerror', e => errors.push(e.message));
await editor.waitForFunction(() => !document.getElementById('refreshEncoders').disabled);
const capabilities = await editor.evaluate(() => rpc('getEncodingCapabilities'));
assert.equal(await editor.locator('#encCodec option').count(), 7);
for (const backend of ['nvenc', 'qsv', 'amf']) assert.equal(await editor.locator(`#encEncoder option[value=${backend}]`).evaluate(o => o.disabled), !capabilities.encoders['h264_' + backend].available);
await editor.locator('#encContainer').selectOption('webm');
assert.equal(await editor.locator('#encCodec').inputValue(), 'vp9');
assert(await editor.locator('#encCodec option[value=h264]').evaluate(o => o.disabled));
assert(await editor.locator('#encAudioCodec option[value=aac]').evaluate(o => o.disabled));
await editor.locator('#encCodec').selectOption('av1');
assert(await editor.locator('#encMode option[value=cbr]').evaluate(o => o.disabled));
await editor.locator('#encPixelFormat').selectOption('yuv420p10le');
await editor.locator('#encPreset').selectOption('ultrafast'); await editor.locator('#encThreads').fill('2'); await editor.locator('#encCrf').fill('30');
await editor.locator('#encAudioCodec').selectOption('opus');
assert(await editor.locator('#encSampleRate').isDisabled());
await editor.screenshot({ path: path.join(directory, 'AV1编码设置.png') });
await editor.locator('#applyEncoding').click();
await main.waitForFunction(() => prefs.container === 'webm' && prefs.encoding.codec === 'av1');
assert.equal(await main.locator('#outputCodec').innerText(), 'AV1 / Opus');
const saved = await main.evaluate(() => ({ encoding: prefs.encoding, media: { audio: state.audio, background: state.background } }));
await main.reload(); await main.waitForFunction(() => window.Startup?.phase === 'ready' && state.dependencies?.ready);
assert.deepEqual(await main.evaluate(() => prefs.encoding), saved.encoding);
await main.evaluate(async s => { loadBackground(s.media.background); await loadAudio(s.media.audio); }, saved);
await main.locator('#resolution').selectOption('480'); await main.locator('#fps').selectOption('24');
await main.locator('#outputDirectory').evaluate((e, v) => e.value = v, directory);
async function render(name, codec, audio) {
  await main.locator('#fileName').fill(name);
  await main.locator('#generateButton').click();
  await main.waitForFunction(() => document.getElementById('renderTitle').textContent !== '正在生成作品', null, { timeout: 180000 });
  assert.equal(await main.locator('#renderTitle').innerText(), '你的作品，完成了', await main.locator('#renderMessage').innerText());
  const output = await main.locator('#renderPath').innerText();
  const probe = JSON.parse(execFileSync('ffprobe', ['-v','error','-show_streams','-of','json',output], { encoding:'utf8' }));
  assert.equal(probe.streams.find(s => s.codec_type === 'video').codec_name, codec);
  assert.equal(probe.streams.find(s => s.codec_type === 'audio').codec_name, audio);
  await main.locator('#renderDialog [data-close]').first().click();
  return { output, probe };
}
const av1 = await render('AV1作品.webm', 'av1', 'opus');
assert.match(av1.probe.streams.find(s => s.codec_type === 'video').pix_fmt, /10/);
editor = await openEncoding(main, browser);
await editor.locator('#encCodec').selectOption('vp8'); await editor.locator('#encAudioCodec').selectOption('vorbis');
assert.equal(await editor.locator('#encAudioBitrate').isVisible(), false);
await editor.locator('#encVorbisQuality').fill('6');
await editor.locator('#applyEncoding').click();
await main.waitForFunction(() => prefs.encoding.codec === 'vp8');
const vorbis = await render('VP8与Vorbis.webm', 'vp8', 'vorbis');
editor = await openEncoding(main, browser);
await editor.locator('#encContainer').selectOption('mov'); await editor.locator('#encCodec').selectOption('prores');
await editor.locator('#encProresProfile').selectOption('4'); await editor.locator('#encAudioCodec').selectOption('pcm24');
assert.equal(await editor.locator('#encMode').isVisible(), false);
assert.equal(await editor.locator('#encAudioBitrate').isVisible(), false);
await editor.screenshot({ path: path.join(directory, 'ProRes编码设置.png') });
await editor.locator('#encodingDialog button[data-close]').last().click();
assert.equal(await main.evaluate(() => prefs.container), 'webm');
editor = await openEncoding(main, browser);
await editor.locator('#encContainer').selectOption('mp4'); await editor.locator('#resetEncoding').click();
await editor.locator('#applyEncoding').click();
await main.waitForFunction(() => prefs.container === 'mp4');
assert.deepEqual(errors, []);
await fs.writeFile(path.join(directory, 'result.json'), JSON.stringify({ passed:true, capabilities, av1, vorbis, errors }, null, 2));
console.log('标题栏扩展编码与 AV1 10 位、VP8/Vorbis WebM 实际导出通过：' + directory);
process.exit(0);
